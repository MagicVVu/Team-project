"""Run stage-4 instrumentation without putting private fixture values in logs.

Build APKs first. Fixture file is generated by seed_execution_android.py via SSH,
captured privately outside Git. This runner only accepts the localhost test tunnel.
"""
import argparse
import json
from pathlib import Path
import subprocess
import urllib.request
import uuid

parser = argparse.ArgumentParser()
parser.add_argument("--adb", required=True)
parser.add_argument("--device", default="emulator-5554")
parser.add_argument("--fixture", type=Path, required=True)
parser.add_argument("--output", type=Path, required=True)
parser.add_argument("--classes", default="com.example.teamapp.AssistantExecutionTest,com.example.teamapp.AssistantExecutionUiTest")
parser.add_argument("--process-restart", action="store_true")
parser.add_argument("--install", action="store_true")
args = parser.parse_args()
fixture = json.loads(args.fixture.read_text(encoding="utf-8-sig"))
health = json.load(urllib.request.urlopen("http://127.0.0.1:18082/api/v1/health", timeout=5))
assert health["version"] == "0.9.0" and health["isolated_test"] is True
args.output.parent.mkdir(parents=True, exist_ok=True)

def adb(*parts):
    return subprocess.run([args.adb, "-s", args.device, *parts], capture_output=True, text=True, encoding="utf-8", errors="replace")

if args.install:
    for apk in ("app/build/outputs/apk/debug/app-debug.apk", "app/build/outputs/apk/androidTest/debug/app-debug-androidTest.apk"):
        result = adb("install", "-r", apk)
        assert result.returncode == 0 and "Success" in result.stdout, "APK install failed"

params = {"executionTestUrl": "http://10.0.2.2:18082", "fixturePhone": fixture["phone"],
    "fixturePassword": fixture["password"], "fixtureHousehold": fixture["household"],
    "fixtureSecondHousehold": fixture["second_household"], "fixtureOtherPhone": fixture["other_phone"]}
logs = []

def instrument(classes, extra=None):
    command = ["shell", "am", "instrument", "-w", "-r"]
    for key, value in {**params, "class": classes, **(extra or {})}.items():
        command.extend(["-e", key, value])
    result = adb(*command, "com.example.teamapp.test/androidx.test.runner.AndroidJUnitRunner")
    safe = (result.stdout + result.stderr).replace(fixture["password"], "[REDACTED]")
    logs.append(safe)
    args.output.write_text("\n".join(logs), encoding="utf-8")
    print(safe)
    assert result.returncode == 0 and "OK (" in safe and "FAILURES!!!" not in safe, "Instrumentation failed; see sanitized evidence"

if args.process_restart:
    namespace = "p4process_" + uuid.uuid4().hex + "_"
    instrument("com.example.teamapp.AssistantProcessRestoreTest#prepareUncertainConfirmedOperation", {"processNamespace": namespace})
    assert adb("shell", "am", "force-stop", "com.example.teamapp").returncode == 0
    instrument("com.example.teamapp.AssistantProcessRestoreTest#restoreAfterActualProcessDeath", {"processNamespace": namespace})
else:
    instrument(args.classes)
