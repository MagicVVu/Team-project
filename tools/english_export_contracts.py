"""Export local bilingual contracts and generated literal assets; no DB/network."""
import hashlib
import json
import os
from pathlib import Path
import sys
from unittest.mock import patch
import autonomous_export_contracts as base

ROOT=Path(__file__).resolve().parents[1]
TARGET=ROOT/'docs/versions/V1-P8.7/contracts'
sys.path.insert(0,str(ROOT/'agent'))


def main():
    base.TARGET=TARGET;base.main()
    from conversation.app import create_app as legacy
    with patch.dict(os.environ,{'AI_SERVICE_TOKEN':'export-only-placeholder','P3_ENGINE':'rules'}):api=legacy(reader=object()).openapi()
    api.update({'x-deployment-status':'local_source_contract_not_deployed','x-conversation-memory-protocol':'conversation-memory-1','x-conversation-dialogue-protocol':'p84-dialogue-1'})
    base.write('legacy-ai-openapi.json',api)
    manifest=json.loads((TARGET/'manifest.json').read_text(encoding='utf-8'))
    manifest.update(stage='V1-P8.7',ai_version='0.8.7',feature='bilingual-assistant',language_protocol='assistant-language-1',languages=['zh-CN','en'])
    manifest['files']['legacy-ai-openapi.json']=hashlib.sha256((TARGET/'legacy-ai-openapi.json').read_bytes()).hexdigest()
    base.write('manifest.json',manifest)
    source=ROOT/'agent/conversation/language/lexicon.json'
    destination=ROOT/'backend/server/app/data/assistant_lexicon.json'
    destination.parent.mkdir(parents=True,exist_ok=True);destination.write_bytes(source.read_bytes())
    from p0.language import UNITS
    kotlin=ROOT/'frontend/app/src/main/java/com/example/teamapp/data/AssistantUnitAliases.kt'
    pairs=',\n        '.join(json.dumps(k,ensure_ascii=False)+' to '+json.dumps(v,ensure_ascii=False) for k,v in UNITS.items())
    kotlin.write_text('package com.example.teamapp.data\n\n/** Generated by english_export_contracts.py from the shared literal unit lexicon. */\nobject AssistantUnitAliases {\n    private val aliases = mapOf(\n        '+pairs+'\n    )\n    fun canonical(value: String) = aliases[value.lowercase(java.util.Locale.ROOT)] ?: value\n}\n',encoding='utf-8')
    print(json.dumps({'feature':'bilingual-assistant','contracts':len(manifest['files']),'deployed':False}))


if __name__=='__main__':main()
